"""
LunaExplainer — Unified base class for all LUNA explainers
==========================================================

Defines a consistent interface for all LUNA explainers across domain types
(e.g., tabular, image, text).

Responsibilities
----------------
- Provide a standardized explanation pipeline.
- Maintain modular architecture:
  • Domain (data preparation + prediction interface)
  • Method (sensitivity computation based on domain-generated neighborhood)
  • Metric (importance computation)
  • Renderer (visualization)
- Support reusable stages:
  • generate_explanation_data() → raw sensitivity data
  • explain_from_data() → compute importances + optional rendering
  • explain_instance() → one-step full pipeline
"""

from __future__ import annotations

from typing import Any, Dict, Optional

from pyparsing import ABC

from luna_xai.core.results import MetricResult
from luna_xai.utils.logging_utils import get_luna_logger
from luna_xai.utils.debug_mixin import DebugMixin


class LunaExplainer(DebugMixin, ABC):
    """
    Base class providing a unified explanation workflow in LUNA XAI.

    Notes
    -----
    Subclasses are expected to implement `generate_explanation_data()` to
    construct domain-specific neighborhood or sensitivity representations.

    Parameters
    ----------
    model : Any
        Predictive model implementing at least a `predict()` method.
    domain : Any
        Domain object responsible for preparing data and providing model access.
    method : Any
        Explanation/sensitivity method.
    metric : Any
        Metric evaluating the method's output.
    renderer : Any, optional
        Optional visualization component.
    output_dir : str, default="results"
        Output directory for artifacts generated by renderers.
    normalizer : Any, optional
        Optional importance-normalization function.
    debug : bool, default False
        If True, enables debug-level logging for this explainer instance.
    """

    def __init__(
        self,
        model: Any,
        domain: Any,
        method: Any,
        metric: Any,
        renderer: Optional[Any] = None,
        output_dir: str = "results",
        normalizer: Optional[Any] = None,
        debug: bool = False,
    ) -> None:
        self.model = model
        self.domain = domain
        self.method = method
        self.metric = metric
        self.renderer = renderer
        self.output_dir = output_dir
        self.normalizer = normalizer

        # Logger for LunaExplainer instances.
        # By default, application code is expected to configure handlers to
        # write logs into a file. If console output is preferred, the
        # "luna_xai" logger can be configured with a StreamHandler or via
        # `configure_luna_logging`.
        self._logger = get_luna_logger("explainer.luna")
        self._debug_enabled: bool = bool(debug)

    # ------------------------------------------------------------------
    # Stage 1 — Generate explanation data
    # ------------------------------------------------------------------
    def generate_explanation_data(self, instance: Any, **kwargs: Any) -> Dict[str, Any]:
        """
        Construct raw explanation data (predictions, neighborhood, sensitivities).

        Notes
        -----
        This method must be implemented by each concrete explainer variant.
        The method should *not* compute feature importances nor perform rendering.

        Returns
        -------
        dict
            {
                "sensitivity_data": {...},
                "predictions": array-like (optional),
                "metadata": {...}
            }
        """
        raise NotImplementedError(
            f"{self.__class__.__name__}.generate_explanation_data() must be implemented by subclasses."
        )

    # ------------------------------------------------------------------
    # Stage 2 — Compute importances and optionally render
    # ------------------------------------------------------------------
    def explain_from_data(
        self,
        explanation_data: Dict[str, Any],
        render: bool = True,
        context: Optional[Dict[str, Any]] = None,
        **kwargs: Any,
    ) -> MetricResult:
        """
        Compute feature importances and optionally render results using precomputed
        explanation data.

        Parameters
        ----------
        explanation_data : dict
            Output from `generate_explanation_data()`.
        render : bool, default=True
            Whether to produce visual output.
        context : dict, optional
            Metadata for the renderer (e.g., instance ID).

        Returns
        -------
        MetricResult
            Final evaluated explanation result.
        """
        self._debug(
            f"Explaining from precomputed data. "
            f"Keys={list(explanation_data.keys())}, render={render}."
        )

        if not explanation_data or "sensitivity_data" not in explanation_data:
            raise ValueError(
                "[LUNA] Missing or invalid explanation_data in explain_from_data()."
            )

        sensitivity_data = explanation_data["sensitivity_data"]

        # Metric evaluation
        self._debug("Computing metric from sensitivity data.")
        result = self.metric.compute(sensitivity_data)
        result.metadata.update(explanation_data.get("metadata", {}))

        # Optional normalization
        if self.normalizer is not None and result.importances:
            self._debug("Applying importance normalization function.")
            result.importances = self.normalizer(result.importances)

        # Optional rendering
        if render and self.renderer is not None:
            self._debug("Rendering explanation result with renderer component.")
            self.renderer.render(result, context=context or {})

        self._debug("Explanation from data completed successfully.")
        return result

    # ------------------------------------------------------------------
    # Stage 3 — Full pipeline
    # ------------------------------------------------------------------
    def explain_instance(self, instance: Any, **kwargs: Any) -> MetricResult:
        """
        One-step pipeline:
        generate explanation data → compute importances → (optional) render.

        This preserves backward compatibility with previous demos.
        """
        self._debug(
            f"Starting full explanation pipeline for instance of type "
            f"{type(instance).__name__}."
        )
        explanation_data = self.generate_explanation_data(instance, **kwargs)
        result = self.explain_from_data(
            explanation_data,
            render=True,
            context={"scope": "local"},
        )
        self._debug("Full explanation pipeline completed successfully.")
        return result

    # ------------------------------------------------------------------
    def __repr__(self) -> str:
        return (
            f"{self.__class__.__name__}("
            f"model={type(self.model).__name__}, "
            f"domain={type(self.domain).__name__}, "
            f"method={type(self.method).__name__}, "
            f"metric={type(self.metric).__name__}, "
            f"renderer={type(self.renderer).__name__ if self.renderer else 'None'})"
        )
