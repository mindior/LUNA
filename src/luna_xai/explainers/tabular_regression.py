"""
TabularRegressionExplainer
==========================

LUNA explainer for tabular regression tasks.

Implements a two-stage pipeline:
1️⃣ generate_explanation_data() → builds raw explanation data (sensitivities, metadata)
2️⃣ explain_from_data()        → computes importances and triggers rendering
"""

from __future__ import annotations

from typing import Any, Dict

import pandas as pd

from luna_xai.core.luna_explainer import LunaExplainer
from luna_xai.core.results import MetricResult
from luna_xai.utils.dataframe import ensure_dataframe


class TabularRegressionExplainer(LunaExplainer):
    """
    LUNA explainer for tabular regression models.

    Typical components
    ------------------
    - Method: DSA (local sampling / PDP-style sensitivity)
    - Metric: CHMetric (Calinski–Harabasz-based feature importance)
    - Renderer: PlotRenderer (or a custom renderer implementation)
    """

    # ------------------------------------------------------------------
    def generate_explanation_data(
        self,
        instance: pd.Series | pd.DataFrame,
        **kwargs: Any,
    ) -> Dict[str, Any]:
        """
        Generate raw explanation data for a single regression instance.

        Produces
        --------
        - sensitivity_data: nested structure produced by the method
              e.g. DSA → { feature: { level: [predictions...] }, ... }
        - metadata: dictionary with trace information (method, metric, etc.)

        Parameters
        ----------
        instance : pd.Series or pd.DataFrame
            Raw instance to be explained (single sample).
        **kwargs : dict
            Extra parameters forwarded to the method's `generate` routine
            (e.g., n_neighbors, n_samples, seed, ...).

        Returns
        -------
        dict
            {
                "sensitivity_data": ...,
                "metadata": {...},
            }
        """
        self._logger.info(
            "[LUNA] Generating explanation data (TabularRegressionExplainer)..."
        )

        # Ensure we are working with a single-row DataFrame
        instance_df = ensure_dataframe(instance)

        # Step 1 — Generate local sensitivity data using the configured method (e.g. DSA)
        sensitivity_data = self.method.generate(
            domain=self.domain,
            instance=instance_df,
            **kwargs,
        )

        # Step 2 — Metadata for traceability / logging
        metadata = {
            "domain": "tabular",
            "task": "regression",
            "method": type(self.method).__name__,
            "metric": type(self.metric).__name__,
            "neighbors": getattr(self.method, "n_neighbors", None),
            "samples": getattr(self.method, "n_samples", None),
        }

        self._debug(
            "Explanation metadata assembled: method=%s, metric=%s, neighbors=%s, samples=%s",
        )
        self._debug(
            "%s | %s | %s | %s"
            % (
                metadata["method"],
                metadata["metric"],
                metadata["neighbors"],
                metadata["samples"],
            )
        )

        # Step 3 — Standardized payload
        return {
            "sensitivity_data": sensitivity_data,
            "metadata": metadata,
        }

    # ------------------------------------------------------------------
    def explain_instance(
        self,
        instance: pd.Series | pd.DataFrame,
        **kwargs: Any,
    ) -> MetricResult:
        """
        Full explanation flow for a single regression instance.

        Pipeline
        --------
        1️⃣ generate_explanation_data() → obtain sensitivity_data + metadata
        2️⃣ explain_from_data()        → compute importances and (optionally) render

        By default, this explainer:
        - sets renderer.plot_type = "importance" before calling explain_from_data
        - leaves additional plots (line/boxplot) to user/demo code

        Parameters
        ----------
        instance : pd.Series or pd.DataFrame
            Raw instance to be explained (single sample).
        **kwargs : dict
            Extra parameters forwarded down to `generate_explanation_data`
            and ultimately to the method's `generate(...)`.

        Returns
        -------
        MetricResult
            Contains feature importances, sensitivity_data, and metadata.
        """
        self._logger.info("[LUNA] Running TabularRegressionExplainer...")

        # Ensure the first plot generated by this explainer is an importance plot.
        if self.renderer is not None:
            self._debug(
                "Setting renderer.plot_type='importance' for primary explanation plot."
            )
            self.renderer.plot_type = "importance"

        # Stage 1 — Build explanation data (no plotting here)
        explanation_data = self.generate_explanation_data(instance, **kwargs)

        # Stage 2 — Compute importances and render (delegated to base class)
        result = self.explain_from_data(
            explanation_data,
            render=True,
            context={
                "scope": "local",
                "instance": ensure_dataframe(instance),
                "idx": kwargs.get("idx", "instance"),
                "show": kwargs.get("show", False),
            },
        )

        self._debug(
            "TabularRegressionExplainer completed for instance with context idx=%s.",
        )
        self._debug(str(kwargs.get("idx", "instance")))

        return result


# ---------------------------------------------------------------------
# Auto-registration
# ---------------------------------------------------------------------
from luna_xai.core.registry import register_component

register_component("explainer", "regression", TabularRegressionExplainer)
