"""
CHMetric — Calinski–Harabasz Feature Importance Metric
=======================================================

This module implements the CH-based feature-importance metric used in
LUNA XAI.

Overview
--------
The CHMetric quantifies how well the predictions separate into distinct
groups when a feature is fixed at different levels (as produced by a
sensitivity method such as DSA). For each feature:

1. The sensitivity generator produces:
       { level_value → predictions_under_that_value }

2. The CH index measures separability between these groups.

3. A sign correction adjusts the importance to reflect whether the
   feature tends to *increase* or *decrease* model output.

Output
------
Returns a `MetricResult` containing:
- raw feature importances (signed CH scores)
- the full sensitivity structure used for computation

Notes
-----
The CH score is always non-negative. The sign adjustment gives the metric
semantic directionality, useful for ranking both "positive" and "negative"
influences on predictions.
"""

from __future__ import annotations

from typing import Dict, Any

from luna_xai.core.base_metric import BaseMetric
from luna_xai.core.results import MetricResult
from luna_xai.utils.metrics import calculate_ch_index, adjust_signal


class CHMetric(BaseMetric):
    """
    Calinski–Harabasz feature-importance metric with directional sign
    correction based on prediction trends.
    """

    def __init__(self, debug: bool = False) -> None:
        """
        Parameters
        ----------
        debug : bool, default=False
            If True, enables debug-level logging for this metric instance.
        """
        super().__init__(debug=debug)

    # ---------------------------------------------------------
    def compute(
        self,
        sensitivity_data: Dict[str, Dict[Any, list]],
        **kwargs: Any,
    ) -> MetricResult:
        """
        Compute CH-based feature importances with sign adjustment.

        Parameters
        ----------
        sensitivity_data : dict
            Mapping of the form:
                {
                  feature_A: { value_1: [preds...], value_2: [...], ... },
                  feature_B: { ... },
                  ...
                }
            Typically generated by a BaseMethod (e.g. DSAMethod).

        Returns
        -------
        MetricResult
            Includes:
            - importances: dict[str, float]
            - sensitivity_data: raw data used to compute importances
        """
        if not isinstance(sensitivity_data, dict):
            raise TypeError(
                "CHMetric.compute expected a dict: {feature: {level: predictions}}"
            )

        self._debug("Starting CH index computation...")

        # -------------------------
        # 1) Compute raw CH values
        # -------------------------
        ch_raw, means_map = calculate_ch_index(
            feature_prediction_dict=sensitivity_data,
        )

        self._debug(f"Raw CH scores: {ch_raw}")
        self._debug(f"Mean prediction map: {means_map}")

        # -------------------------
        # 2) Add sign from mean trends
        # -------------------------
        ch_signed = adjust_signal(means=means_map, ch_values=ch_raw)

        self._debug(f"Signed CH scores: {ch_signed}")

        # -------------------------
        # 3) Wrap results
        # -------------------------
        return MetricResult(
            importances=ch_signed,
            sensitivity_data=sensitivity_data,
            metadata={"metric": "CH"},
        )


# ---------------------------------------------------------------------
# Auto-registration in LUNA registry
# ---------------------------------------------------------------------
from luna_xai.core.registry import register_component

register_component("metric", "ch", CHMetric)
